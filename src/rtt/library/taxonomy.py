"""Words the library uses to describe an item: capabilities, kinds, classes and sim status.

* **Capability tags** (:data:`CAPABILITIES`) say which task primitives an item can serve. The
  Studio's combination search prunes candidates per step with them (``docs/LIBRARY.md``).
* **Kind** (:data:`KINDS`): the item's form, in plain words on screen (:data:`KIND_TITLES`).
* **Class** (:data:`CLASSES`): open hardware you can build, a simulation model of a product
  (shipped under a generic name), a sim-only proxy, or our own generated part.
* **Sim status** (:data:`SIM_STATUSES`), explicit for every item:

  * ``native``: an upstream simulation model (MJCF, or URDF/SDF converted to MJCF by us);
  * ``proxy``: no upstream model, so we generate one: a rigid body from the item's own mesh
    (CoACD convex pieces), or a mapping onto an existing family (a suction cup onto the
    seal-gated suction family). Rigid proxies are fidelity ``rigid``; family proxies keep the
    family's fidelity;
  * ``visual_only``: files and a 3D preview, no physics. Articulated designs without an upstream
    model, and compliant parts whose compliance we do not model yet;
  * ``none``: listed with a link only (files not mirrored), with the reason.
"""

